// Завдання 1. Топ-10 виконавців за середньою популярністю
// Знайдіть виконавців, у яких є хоча б 5 треків. 
// Для кожного виконавця порахуйте середню популярність його треків. 
// Потім відсортуйте за спаданням та виберіть топ-10 виконавців. 
// Вивід повинен включати ім’я виконавця та його середню популярність.

db.tracks.aggregate([
    { $unwind: "$artists" }, // Розгортаємо масив артистів
    {
        $group: {
            _id: "$artists", // Групуємо за ім'ям артиста
            avgPopularity: { $avg: "$popularity" }, // Середня популярність
            trackCount: { $sum: 1 } // Рахуємо кількість треків
        }
    },
    {
        $match: {
            trackCount: { $gte: 5 } // Вибираємо артистів з хоча б 5 треками
        }
    },
    {
        $project: {
            _id: 0, // Не виводимо _id
            artist: "$_id", // Виводимо ім'я артиста
            avgPopularity: 1 // Виводимо середню популярність
        }
    },
    { $sort: { avgPopularity: -1 } }, // Сортуємо за середньою популярністю у спадному порядку
    { $limit: 10 } // Виводимо топ-10 артистів
]);


//Завдання 2. Розподіл треків за настроєм
//Кожному треку присвойте настрій на основі двох полів: valence (позитивність) та energy:
//  високий valence + висока energy → happy
//  низький valence + висока energy → angry
//  високий valence + низька energy → calm
//  низький valence + низька energy → sad 
// Порахуйте, скільки треків потрапило до кожної категорії, 
// та виведіть таблицю з настроєм і кількістю треків.

db.tracks.aggregate([
    {
        $project: {
            mood: {
                $switch: {
                    branches: [
                        {
                            case: { $and: [ { $gt: ["$audio_features.valence", 0.5] }, { $gt: ["$audio_features.energy", 0.5] } ] },
                            then: "happy"
                        },
                        {
                            case: { $and: [ { $lte: ["$audio_features.valence", 0.5] }, { $gt: ["$audio_features.energy", 0.5] } ] },
                            then: "angry"
                        },
                        {
                            case: { $and: [ { $gt: ["$audio_features.valence", 0.5] }, { $lte: ["$audio_features.energy", 0.5] } ] },
                            then: "calm"
                        },
                        {
                            case: { $and: [ { $lte: ["$audio_features.valence", 0.5] }, { $lte: ["$audio_features.energy", 0.5] } ] },
                            then: "sad"
                        }
                    ],
                    default: "unknown"  
                }
            }
        }
    },
    {
        $group: {
            _id: "$mood", // Групуємо за настроєм
            count: { $sum: 1 } // Рахуємо кількість треків у кожному настрої
        }
    },
    {   
        $project: {
            _id: 0, // Не виводимо _id
            mood: "$_id", // Виводимо настрій
            count: 1 // Виводимо кількість треків
        }
    }
]);

//  Завдання 3. Найбільш «танцювальний» жанр
// Визначте, який музичний жанр найкраще підходить для танців. 
// Для цього згрупуйте треки за жанрами та обчисліть середні значення 
//  танцювальності (danceability), 
//  енергії (energy) 
//  та позитивності (valence).
// Відфільтруйте жанри, в яких налічується менше 100 треків, 
// щоб забезпечити статистичну надійність. У результаті виведіть:
//  назву жанру,
//  середню танцювальність (avg_danceability),
//  середню енергію (avg_energy),
//  середню позитивність (avg_valence),
//  кількість треків у жанрі

db.tracks.aggregate([
    { $unwind: "$track_genre" }, // Розгортаємо масив жанрів
    {
        $group: {
            _id: "$track_genre", // Групуємо за жанром
            avg_danceability: { $avg: "$audio_features.danceability" }, // Середня танцювальність
            avg_energy: { $avg: "$audio_features.energy" }, // Середня енергія
            avg_valence: { $avg: "$audio_features.valence" }, // Середня позитивність
            trackCount: { $sum: 1 } // Рахуємо кількість треків у жанрі
        }
    },
    {
        $match: {
            trackCount: { $gte: 100 } // Відфільтровуємо жанри з менше ніж 100 треками
        }
    },
    {
        $project: {
            _id: 0, // Не виводимо _id
            genre: "$_id", // Виводимо назву жанру
            avg_danceability: 1, // Виводимо середню танцювальність
            avg_energy: 1, // Виводимо середню енергію
            avg_valence: 1, // Виводимо середню позитивність
            trackCount: 1 // Виводимо кількість треків у жанрі
        }
    },
    { $sort: { avg_danceability: -1 } } // Сортуємо за середньою танцювальністю у спадному порядку
]);